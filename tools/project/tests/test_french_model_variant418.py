    def test_webs_selected_timing_descriptors_and_binding(self):
        archive_path = family435.ROOT / f"game/{self.region}/DATA/MODEL.MRG"
        if not archive_path.exists():
            self.skipTest(f"legal {self.region} MODEL input required")
        self.assertEqual(0xF60 + 0x27C, 0x11DC)
        self.assertEqual(0x1D4 + 8 * 4, 0x1F4)
        with archive_path.open("rb") as archive:
            for module in self.modules:
                row = self.instances[module["name"]]
                base = int(module["load_address"], 0)
                archive.seek(module["sector_offset"] * 2048)
                data = archive.read(20480)
                for offset, word in ((0x3B0, 0x00003821), (0x3C0, 0x00009821), (0x3C8, 0x02603021)):
                    self.assertEqual(struct.unpack_from("<I", data, offset)[0], word)
                table = base + 0x3218
                self.assertEqual(struct.unpack_from("<II", data, 0xA0),
                                 (0x3C020000 | ((table + 0x8000) >> 16 & 0xFFFF),
                                  0x24420000 | (table & 0xFFFF)))
                archive.seek((int(row["record"]) * 276 + 275) * 2048 + 0x114)
                command, = struct.unpack("<i", archive.read(4))
                self.assertEqual(command, 584002)
                self.assertEqual(command, int(row["command_word"]))
                descriptor = 0x3218 + command % 1000 * 48
                self.assertEqual(descriptor, 0x3278)
                self.assertEqual(struct.unpack_from("<III", data, descriptor + 0x1C), (30, 110, 120))
                for call, target in ((0xE3C, 0x1760), (0xE44, 0x1C9C)):
                    self.assertEqual(struct.unpack_from("<II", data, call),
                                     (0x0C000000 | ((base + target) >> 2 & 0x3FFFFFF), 0x02602021))
                name = "ratan2" if self.region == "france" else "func_french_80089928"
                self.assertIn(f"{name} = 0x80089928;",
                              (family435.ROOT / module["linker_symbols"]).read_text())
